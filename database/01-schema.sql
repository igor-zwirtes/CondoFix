
-- =====================================================
-- 1. USUARIOS E CONTROLE DE ACESSO
-- =====================================================

CREATE TABLE "USUARIOS" (
    usrid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usrnam VARCHAR(255) NOT NULL,
    usrphn VARCHAR(20),
    usreml VARCHAR(255) NOT NULL,
    usrpsw VARCHAR(255) NOT NULL,

    CONSTRAINT PK_USUARIOS PRIMARY KEY (usrid),
    CONSTRAINT UQ_USUARIOS_EMAIL UNIQUE (usreml)
);

-- Papeis da aplicacao
CREATE TABLE "ROLES" (
    roleid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    rolenam VARCHAR(50) NOT NULL,
    roledesc TEXT,

    CONSTRAINT PK_ROLES PRIMARY KEY (roleid),
    CONSTRAINT UQ_ROLES_NOME UNIQUE (rolenam)
);

-- Associacao entre usuarios e papeis
CREATE TABLE "USUARIO_ROLES" (
    usrid INTEGER NOT NULL,
    roleid INTEGER NOT NULL,

    CONSTRAINT PK_USUARIO_ROLES
        PRIMARY KEY (usrid, roleid),

    CONSTRAINT FK_USUARIO_ROLES_USUARIOS
        FOREIGN KEY (usrid)
        REFERENCES "USUARIOS" (usrid)
        ON DELETE CASCADE,

    CONSTRAINT FK_USUARIO_ROLES_ROLES
        FOREIGN KEY (roleid)
        REFERENCES "ROLES" (roleid)
        ON DELETE CASCADE
);

-- =====================================================
-- 2. PERFIS DOS USUARIOS
-- =====================================================

CREATE TABLE "ADMINISTRADORES" (
    usrid INTEGER NOT NULL,
    admcpf CHAR(11) NOT NULL,

    CONSTRAINT PK_ADMINISTRADORES PRIMARY KEY (usrid),
    CONSTRAINT UQ_ADMINISTRADORES_CPF UNIQUE (admcpf),

    CONSTRAINT FK_ADMINISTRADORES_USUARIOS
        FOREIGN KEY (usrid)
        REFERENCES "USUARIOS" (usrid)
        ON DELETE CASCADE
);

CREATE TABLE "APARTAMENTOS" (
    aptid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    aptnum VARCHAR(8) NOT NULL,
    aptflr VARCHAR(4) NOT NULL,
    aptblk VARCHAR(4) NOT NULL,

    CONSTRAINT PK_APARTAMENTOS PRIMARY KEY (aptid),

    CONSTRAINT UQ_APARTAMENTOS
        UNIQUE (aptnum, aptflr, aptblk)
);

CREATE TABLE "MORADORES" (
    usrid INTEGER NOT NULL,
    aptid INTEGER NOT NULL,
    rescpf CHAR(11) NOT NULL,

    CONSTRAINT PK_MORADORES PRIMARY KEY (usrid),

    CONSTRAINT UQ_MORADORES_CPF UNIQUE (rescpf),

    CONSTRAINT FK_MORADORES_USUARIOS
        FOREIGN KEY (usrid)
        REFERENCES "USUARIOS" (usrid)
        ON DELETE CASCADE,

    CONSTRAINT FK_MORADORES_APARTAMENTOS
        FOREIGN KEY (aptid)
        REFERENCES "APARTAMENTOS" (aptid)
        ON DELETE RESTRICT
);

CREATE TABLE "PRESTADORES_SERVICO" (
    usrid INTEGER NOT NULL,
    pvdcpf CHAR(11),
    pvdcnpj CHAR(14),
    pvdcmp VARCHAR(255) NOT NULL,

    CONSTRAINT PK_PRESTADORES_SERVICO PRIMARY KEY (usrid),

    CONSTRAINT FK_PRESTADORES_USUARIOS
        FOREIGN KEY (usrid)
        REFERENCES "USUARIOS" (usrid)
        ON DELETE CASCADE,

    CONSTRAINT CK_PRESTADORES_DOCUMENTO
        CHECK (pvdcpf IS NOT NULL OR pvdcnpj IS NOT NULL),

    CONSTRAINT CK_PRESTADORES_CPF_CNPJ
        CHECK (pvdcpf IS NULL OR pvdcnpj IS NULL)
);

CREATE UNIQUE INDEX UQ_PRESTADORES_CPF
    ON "PRESTADORES_SERVICO" (pvdcpf)
    WHERE pvdcpf IS NOT NULL;

CREATE UNIQUE INDEX UQ_PRESTADORES_CNPJ
    ON "PRESTADORES_SERVICO" (pvdcnpj)
    WHERE pvdcnpj IS NOT NULL;


-- =====================================================
-- 3. TABELAS DE DOMINIO
-- =====================================================

CREATE TABLE "CATEGORIAS_SOLICITACAO" (
    catid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    catnom VARCHAR(100) NOT NULL,

    CONSTRAINT PK_CATEGORIAS PRIMARY KEY (catid),
    CONSTRAINT UQ_CATEGORIAS_NOME UNIQUE (catnom)
);

CREATE TABLE "PRIORIDADES_SOLICITACAO" (
    priid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    prinom VARCHAR(30) NOT NULL,

    CONSTRAINT PK_PRIORIDADES PRIMARY KEY (priid),
    CONSTRAINT UQ_PRIORIDADES_NOME UNIQUE (prinom)
);

CREATE TABLE "STATUS_SOLICITACAO" (
    stsid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    stsnom VARCHAR(30) NOT NULL,

    CONSTRAINT PK_STATUS PRIMARY KEY (stsid),
    CONSTRAINT UQ_STATUS_NOME UNIQUE (stsnom)
);

CREATE TABLE "TIPOS_ALTERACAO" (
    typid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    typnom VARCHAR(50) NOT NULL,

    CONSTRAINT PK_TIPOS_ALTERACAO PRIMARY KEY (typid),
    CONSTRAINT UQ_TIPOS_ALTERACAO_NOME UNIQUE (typnom)
);

-- =====================================================
-- 4. SOLICITACOES DE MANUTENCAO
-- =====================================================

CREATE TABLE "SOLICITACOES" (
    soid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    usrid INTEGER NOT NULL,
    aptid INTEGER NOT NULL,
    pvdid INTEGER,
    sodcp TEXT NOT NULL,
    catid INTEGER NOT NULL,
    priid INTEGER NOT NULL,
    stsid INTEGER NOT NULL,
    soopn TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    socls TIMESTAMP,

    CONSTRAINT PK_SOLICITACOES PRIMARY KEY (soid),

    CONSTRAINT FK_SOLICITACOES_USUARIOS
        FOREIGN KEY (usrid)
        REFERENCES "USUARIOS" (usrid)
        ON DELETE RESTRICT,

    CONSTRAINT FK_SOLICITACOES_APARTAMENTOS
        FOREIGN KEY (aptid)
        REFERENCES "APARTAMENTOS" (aptid)
        ON DELETE RESTRICT,

    CONSTRAINT FK_SOLICITACOES_PRESTADORES
        FOREIGN KEY (pvdid)
        REFERENCES "PRESTADORES_SERVICO" (usrid)
        ON DELETE RESTRICT,

    CONSTRAINT FK_SOLICITACOES_CATEGORIAS
        FOREIGN KEY (catid)
        REFERENCES "CATEGORIAS_SOLICITACAO" (catid)
        ON DELETE RESTRICT,

    CONSTRAINT FK_SOLICITACOES_PRIORIDADES
        FOREIGN KEY (priid)
        REFERENCES "PRIORIDADES_SOLICITACAO" (priid)
        ON DELETE RESTRICT,

    CONSTRAINT FK_SOLICITACOES_STATUS
        FOREIGN KEY (stsid)
        REFERENCES "STATUS_SOLICITACAO" (stsid)
        ON DELETE RESTRICT,

    CONSTRAINT CK_SOLICITACOES_DATAS
        CHECK (socls IS NULL OR socls >= soopn)
);

CREATE INDEX IDX_SOLICITACOES_USUARIO
    ON "SOLICITACOES" (usrid);

CREATE INDEX IDX_SOLICITACOES_APARTAMENTO
    ON "SOLICITACOES" (aptid);

CREATE INDEX IDX_SOLICITACOES_PRESTADOR
    ON "SOLICITACOES" (pvdid);

CREATE INDEX IDX_SOLICITACOES_PRIORIDADE
    ON "SOLICITACOES" (priid);

CREATE INDEX IDX_SOLICITACOES_STATUS
    ON "SOLICITACOES" (stsid);

CREATE INDEX IDX_SOLICITACOES_CATEGORIA
    ON "SOLICITACOES" (catid);


-- =====================================================
-- 5. HISTORICO DE ALTERACOES
-- =====================================================

CREATE TABLE "ALTERACOES" (
    altid INTEGER GENERATED BY DEFAULT AS IDENTITY,
    soid INTEGER NOT NULL,
    usrid INTEGER NOT NULL,
    typid INTEGER NOT NULL,
    altdcp TEXT NOT NULL,
    alttim TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT PK_ALTERACOES PRIMARY KEY (altid),

    CONSTRAINT FK_ALTERACOES_SOLICITACOES
        FOREIGN KEY (soid)
        REFERENCES "SOLICITACOES" (soid)
        ON DELETE CASCADE,

    CONSTRAINT FK_ALTERACOES_USUARIOS
        FOREIGN KEY (usrid)
        REFERENCES "USUARIOS" (usrid)
        ON DELETE RESTRICT,

    CONSTRAINT FK_ALTERACOES_TIPOS
        FOREIGN KEY (typid)
        REFERENCES "TIPOS_ALTERACAO" (typid)
        ON DELETE RESTRICT
);

CREATE INDEX IDX_ALTERACOES_SOLICITACAO
    ON "ALTERACOES" (soid);

CREATE INDEX IDX_ALTERACOES_USUARIO
    ON "ALTERACOES" (usrid);


-- =====================================================
-- 6. AVALIACOES
-- =====================================================

CREATE TABLE "AVALIACOES" (
    soid INTEGER NOT NULL,
    evascr INTEGER NOT NULL,
    evanot TEXT,

    CONSTRAINT PK_AVALIACOES PRIMARY KEY (soid),

    CONSTRAINT CK_AVALIACOES_NOTA
        CHECK (evascr BETWEEN 0 AND 5),

    CONSTRAINT FK_AVALIACOES_SOLICITACOES
        FOREIGN KEY (soid)
        REFERENCES "SOLICITACOES" (soid)
        ON DELETE CASCADE
);
